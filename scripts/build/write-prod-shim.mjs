#!/usr/bin/env node
/**
 * Writes `dist/index.cjs` — the production entrypoint invoked as
 * `node ./dist/index.cjs` (Dockerfile CMD, `npm start`, Replit Autoscale).
 *
 * §L-442 (2026-08-09) — NO MORE tsx, NO MORE child process.
 * ---------------------------------------------------------
 * This shim used to `spawn(process.execPath, ['--import', 'tsx', 'server.js'])`.
 * Two costs, both paid on EVERY cold boot, i.e. on every scale-out event:
 *   1. a second Node process, with signal forwarding to get wrong; and
 *   2. tsx registration + on-the-fly transpilation of the workspace TypeScript
 *      reachable from server.js, before `httpServer.listen()` was ever reached.
 *
 * `server.js` and all of `server/**` are already plain JavaScript — the loader
 * existed solely for two `@pryzm/*` imports whose package `main` is a `.ts` file
 * (`@pryzm/crash-reporter`, `@pryzm/file-format/server`). Those are now
 * precompiled by `scripts/build/build-server-deps.mjs` and swapped into
 * node_modules by `scripts/build/apply-server-deps-overlay.mjs`, so the shim is
 * just an in-process `import()` of the real entry point.
 *
 * MEASURED delta for those two imports on the dev box (median of 5):
 *   tsx        1.94 s warm / 4.84 s cold
 *   precompiled 0.145 s total process time (~2 ms over a bare `node -e ""`)
 *
 * Why `.cjs` at all, when it only does a dynamic import? Because the filename is
 * baked into the Dockerfile CMD, `package.json#scripts.start` and the Replit
 * deployment config. Keeping it costs one file and breaks nothing; renaming it
 * means changing three deployment surfaces at once.
 *
 * The shim deliberately does NOT swallow errors: an import failure must exit
 * non-zero so Fly's health gate refuses the deploy rather than parking a dead
 * machine in rotation.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
// A.U.20 — script lives at scripts/build/; repoRoot is two levels up.
const repoRoot = resolve(here, '..', '..');
const outDir = resolve(repoRoot, 'dist');
const outFile = resolve(outDir, 'index.cjs');

const shim = `// AUTO-GENERATED by scripts/build/write-prod-shim.mjs — do not edit by hand.
// §L-442: boots server.js IN-PROCESS with plain node. No tsx, no child process.
// The workspace TypeScript server.js used to pull in is precompiled into
// node_modules/@pryzm/* by the image build (see build-server-deps.mjs).
const { pathToFileURL } = require("node:url");
const { join } = require("node:path");

const entry = pathToFileURL(join(__dirname, "..", "server.js")).href;

import(entry).catch((err) => {
  // Loud + non-zero: a boot failure must fail the deploy health gate, never
  // leave a half-started process bound to the port.
  console.error("[prod-shim] failed to boot server.js:", err && err.stack ? err.stack : err);
  process.exit(1);
});
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, shim);
console.log(`[write-prod-shim] wrote ${outFile} (${shim.length} bytes)`);
