// WHY A LEDGER, AND WHY IT IS CODE RATHER THAN A COMMENT
// ═════════════════════════════════════════════════════════════════════════════
//
// The rule this file makes structural was already TRUE and already WRITTEN — in
// three separate prose places, none of which a compiler or a gate can read:
//
//   · `tools/texture-pipeline/README.md`   — "No file from pascalorg/editor is
//     copied, downloaded, vendored or derived from. We take the taxonomy only."
//   · `tools/texture-pipeline/sources/materials.json` `$comment` — the same
//     sentence, in a JSON comment key.
//   · `docs/04-reference/PASCAL-FINISHES-RESEARCH.md` §0.2 — the measurement
//     behind it.
//
// ⛔ A rule stated in three prose places and enforced in one script's allowlist
// is enforced for exactly the path that runs that script. It says nothing about a
// row typed straight into `materialCatalog.ts`, which is how EVERY procedural row
// and every hand-authored row arrives. So the ledger moves next to the DATA.
//
// ⭐ THE SHAPE IS NOT INVENTED HERE. It is lane RATE53's, adopted deliberately:
// `packages/core-app-model/src/quantities/RegionalRates.ts` established that a
// source carries a three-valued licence verdict PLUS `licenceNote` — "the
// sentence in the licence that decided it" — and that `NOT_ESTABLISHED` is the
// honest default and is NOT a synonym for "probably fine". Minting a second
// spelling of that idea one package over would be C100 §1.1's own "MUST NOT mint
// a second enumeration", applied to licensing instead of to colour.
//
// ⚠ STILL PURE (P5 / C03 §1.2). Plain strings and frozen arrays. No I/O, no
// THREE, no DOM, no network. Nothing here READS a licence; it RECORDS that a
// human did, and what the licence said.
// ═════════════════════════════════════════════════════════════════════════════

/**
 * ⛔ THE FIELD THAT DECIDES WHETHER A CATALOGUE ROW MAY SHIP AT ALL.
 *
 * Adopted verbatim from `RateLicenceStatus` (lane RATE53) so the repository has
 * ONE licence vocabulary rather than one per subsystem.
 */
export type MaterialLicenceStatus =
    /** A licence text was READ and permits redistribution inside this product. Cite it in `licenceNote`. */
    | 'CLEARED_FOR_REDISTRIBUTION'
    /** A licence text was READ and FORBIDS redistribution (or does not grant it). The bytes stay out. */
    | 'LICENSED_NOT_REDISTRIBUTABLE'
    /**
     * ⛔ Nobody has read a licence that covers this, or the chain of title cannot be
     * established. NOT "probably fine". No shipped row may name an upstream in this
     * state, and `unclearedMaterialUpstreams()` exists to prove none does.
     */
    | 'NOT_ESTABLISHED';

/**
 * WHAT we took from an upstream. ⭐ This axis is SEPARATE from the licence verdict
 * on purpose, and separating them is the whole finding of lane PASCALMAT58:
 *
 * `pascalorg/editor` is ONE repository with TWO different answers. Its TypeScript
 * is MIT and reusable; its 288 texture binaries have no statement of origin
 * anywhere in a complete tree walk, and MIT covers what the authors had the right
 * to license — it is not a warranty over third-party binaries someone committed
 * into `public/`. Collapsing "the repo is MIT" into "therefore the pixels are
 * ours to ship" is exactly the conflation this type prevents at the type level.
 */
export type MaterialUpstreamTake =
    /** Bitmap files that ship to a user's browser. The strictest case. */
    | 'PIXELS'
    /** Source code or data structures copied or adapted. */
    | 'CODE'
    /**
     * The IDEA of which finishes a building editor needs, and nothing expressive.
     * ⭐ A taxonomy is an idea, not an expression, and is not a licensing question
     * at all — recorded anyway, because "we looked at it" is a fact a diligence
     * review is entitled to see stated rather than inferred.
     */
    | 'TAXONOMY'
    /** Generated by our own arithmetic, or authored by us from trade product ranges. */
    | 'ORIGINAL';

/** Stable ids for every upstream any catalogue row may name. */
export type MaterialUpstreamId =
    | 'pryzm-authored'
    | 'pryzm-procedural'
    | 'ambientcg'
    | 'pascalorg-editor-taxonomy'
    | 'pascalorg-editor-textures';

/**
 * One upstream a material's data or bytes may have come from.
 *
 * ⛔ `licenceNote` is `null` ONLY where `licence` is `NOT_ESTABLISHED`. A verdict
 * with no sentence behind it is an opinion, and RATE53 already ruled that an
 * opinion may not stand in for a licence reading.
 */
export interface MaterialUpstream {
    readonly id: MaterialUpstreamId;
    /** The upstream in its own name, as it would be cited in a diligence review. */
    readonly name: string;
    /** Where to go and check. `null` only for our own work. */
    readonly homepage: string | null;
    /** SPDX id where one applies, else a short description. `null` when unestablished. */
    readonly licence: string | null;
    readonly status: MaterialLicenceStatus;
    /**
     * ⭐ THE SENTENCE IN THE LICENCE THAT DECIDED IT — quoted, not paraphrased.
     * A paraphrase is a second reading of a text the reader cannot see.
     */
    readonly licenceNote: string | null;
    /** ISO `YYYY-MM-DD` a human read the licence text. `null` when unread. */
    readonly verifiedOn: string | null;
    /** What we took. See {@link MaterialUpstreamTake}. */
    readonly take: MaterialUpstreamTake;
    /**
     * ⭐ Whether shipping this obliges us to reproduce a notice. When TRUE the text
     * in `attributionText` MUST appear in the shipped `NOTICE.md`, and
     * `materialUpstreamsRequiringNotice()` is what proves it does.
     */
    readonly attributionRequired: boolean;
    /** Exactly what must be reproduced. `null` iff `attributionRequired` is false. */
    readonly attributionText: string | null;
    /** Why this verdict, in one line — the reasoning, kept beside the quote. */
    readonly rationale: string;
}

