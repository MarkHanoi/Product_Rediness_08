const BY_ID: ReadonlyMap<MaterialUpstreamId, MaterialUpstream> = new Map(
    MATERIAL_UPSTREAMS.map((u) => [u.id, u]),
);

/** The one lookup. ⛔ Do not hand-roll `.find()` over the array (C100 §1.3). */
export function findMaterialUpstream(id: string): MaterialUpstream | undefined {
    return BY_ID.get(id as MaterialUpstreamId);
}

/**
 * ⛔ THE PREDICATE A SHIPPED ROW MUST SATISFY.
 *
 * `NOT_ESTABLISHED` and `LICENSED_NOT_REDISTRIBUTABLE` both mean "the bytes or the
 * expression stay out"; only the reason differs, and the reason is in the row.
 */
export function isUpstreamClearedToShip(id: string): boolean {
    return findMaterialUpstream(id)?.status === 'CLEARED_FOR_REDISTRIBUTION';
}

/**
 * Every upstream whose licence has NOT been read and cleared.
 *
 * ⭐ Shaped exactly like RATE53's `unclearedBuildingCostModels()` — a non-empty
 * result is not a warning, it is a statement that this repository may be
 * redistributing something nobody established a right to. It is expected to be
 * NON-empty here (the Pascal textures row lives in it deliberately), which is why
 * the enforcement is "no ROW names an uncleared upstream", not "the ledger is
 * empty". A ledger with no refusals in it has not been used.
 */
export function unclearedMaterialUpstreams(): readonly MaterialUpstream[] {
    return MATERIAL_UPSTREAMS.filter((u) => u.status !== 'CLEARED_FOR_REDISTRIBUTION');
}

/**
 * Every upstream whose licence obliges us to reproduce a notice.
 *
 * ⭐ THIS IS WHAT MAKES ATTRIBUTION STRUCTURAL RATHER THAN A COURTESY. The shipped
 * `NOTICE.md` is checked against this list by
 * `tools/ga-gate/check-material-single-source.ts` ARM F, so deleting the notice
 * breaks a gate instead of quietly breaching a licence condition.
 */
export function materialUpstreamsRequiringNotice(): readonly MaterialUpstream[] {
    return MATERIAL_UPSTREAMS.filter((u) => u.attributionRequired);
}
