/**
 * PoolPlanToolHandler — §FIX-POOL-UNREACHABLE (L-5210..L-5216) · ADR-0124 · C100
 *
 * THE PLAN-VIEW ROUTE THAT MAKES A SWIMMING POOL REACHABLE. It is the third of the
 * four axes L-5200 measured as closed:
 *
 *   1. no `PoolStore` was ever constructed              → closed by PluginRegistry
 *   2. no `pool`/`water` storeKey, so the bus threw     → closed by PluginRegistry
 *   3. NOTHING DISPATCHED `pool.create`                 → CLOSED HERE
 *   4. the AI chat classifies `pool.create` class B     → still open (L-5206)
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * ⭐ THIS FILE CONTAINS NO POOL GEOMETRY. That is the point.
 * ═══════════════════════════════════════════════════════════════════════════════
 * It draws an OUTLINE and dispatches ONE command. Every dimension, every wall,
 * the floor slab, the water body and the hole in the host slab are computed by
 * `buildPoolAssembly()` in `@pryzm/geometry-pool`, which is pure and already
 * tested. There is no second assembly here, no hole-punching routine, and not one
 * dimensional literal — `resolvePoolDimensions()` is the only source of a pool
 * dimension in this repo and `poolNoLiterals.test.ts` enforces that at source level.
 *
 * ⭐ AND NO NEW SHAPE VOCABULARY. The six modes come from `activePoolDrawMode`,
 * which is the union of two EXISTING `@pryzm/geometry-slab` unions, and the
 * closed-loop rings are generated by `boundaryLoopVertices()` — the same generator
 * the slab, floor-finish and ceiling tools call. The founder asked for
 * "linear, ortho — but also circular, ellipse, rectangular"; all six are served by
 * machinery that already shipped, so the strip cannot offer a shape the generator
 * does not implement (§FIX-STAIR-SHAPE-DESYNC's lesson).
 *
 * ── THE ONE GENUINELY POOL-SPECIFIC PROBLEM: WHICH SLAB IS THE HOST? ──────────
 * A pool is cut INTO something. `CreatePoolHandler.canExecute` refuses when
 * `ctx.stores.slab[hostSlabId]` is absent — "a pool with no slab to cut into is not
 * a pool; it is a hole in the air" — so this handler must name a host BEFORE it
 * dispatches, and must refuse legibly when it cannot.
 *
 * Resolution order, strongest first:
 *   1. GEOMETRY — the slab on the active level whose boundary CONTAINS the pool
 *      outline's centroid. This is the natural gesture: draw the pool on the
 *      terrace and the terrace is the host, with nothing to select first.
 *   2. SELECTION — an explicitly selected slab, as the TIE-BREAK when two or more
 *      slabs contain the outline, and as the OVERRIDE for a pool deliberately cut
 *      into a slab it is not centred on.
 *   3. REFUSE, BY NAME (C16 CA-18). Never "silently create nothing", never invent a
 *      host, and never pick one of several arbitrarily.
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * ⛔ §FIX-POOL-HOST-FROM-GEOMETRY (L-10820) — STEPS 1 AND 2 WERE BOTH DEAD, AND
 *    STEP 3 TOLD THE ARCHITECT TO USE THEM.
 * ═══════════════════════════════════════════════════════════════════════════════
 * THE FOUNDER: *"check the pool — is not working — no matter if i select the slab
 * before or after (actually there should not be the need of selecting the slab — it
 * should be like when you place a window in a wall — you don't need to select the
 * wall — same)."* Both orders failed, and they failed for two INDEPENDENT reasons:
 *
 *   • GEOMETRY (step 1) searched for a field no store has. `_candidateSlabs` read
 *     `rec.boundary`, but the legacy `SlabData` the browser actually holds spells its
 *     outline `polygon: {x, y}[]` — LOCAL, with `y` on the Z axis — and has no
 *     `boundary` field at all. Its other source, `window.runtime.stores['slab']`, is
 *     `undefined` in every session: the composed runtime's `stores` is a `StoresSlot`
 *     with five NAMED members and no index signature. Both reads were kept alive
 *     purely by a hand-written `window as unknown as …` cast.
 *   • SELECTION (step 2) was gated on `id.startsWith('slab')`, and his slab's id is
 *     `c0ba8bda-77a4-4f24-a248-fbc78aebed56` — a bare UUID from the 3-D `SlabTool`.
 *
 * Each is documented at the method that carried it. The lesson they share is the one
 * the test file states: every pool suite before this was green because each installed
 * `runtime.stores.slab` with a `boundary` field — a fixture built from this header's
 * CLAIMS rather than from the runtime, which therefore could not falsify them.
 *
 * ⚠ MEASURED CAVEAT, STATED RATHER THAN HIDDEN. The lookup reads the plugin slab
 * DTO store when the runtime exposes it, and falls back to the legacy
 * `window.slabStore`. Those are two stores and this repo already knows they can
 * diverge (the "detached-DTO-mirror condition",
 * PLUGIN-SDK-AND-EXTERNAL-API-READINESS-REGISTER §374). A slab present ONLY in the
 * legacy store will pass this handler's check and then be REFUSED by
 * `canExecute` — which is why the dispatch's rejection is caught and surfaced
 * verbatim below rather than swallowed. That is honest failure, not a fix for the
 * duality; the duality is pre-existing and is recorded as L-5215.
 */

