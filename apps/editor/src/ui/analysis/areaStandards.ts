/**
 * areaStandards — which measured-area standard PRYZM is reporting under, and
 * what each of its classes can ACTUALLY be measured from today.
 *
 * Layer Affected:  UI — Analysis surface (L7)
 * File:            apps/editor/src/ui/analysis/areaStandards.ts
 * ADR:             ADR-0343 §D.6 (honesty) · §U.3 (the open standard decision)
 * SPEC:            SPEC-ANALYSIS-SURFACE-AND-WIDGETS §4.5
 * Issue log:       L-3640 (this module) · L-3641 (the centreline finding)
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * ⭐ THE MEASUREMENT THAT DECIDED THE SHAPE OF THIS FILE
 * ═════════════════════════════════════════════════════════════════════════════
 * The `gfa-nia` refusal card lists three missing things, and its THIRD reads:
 * *"Wall-centreline vs internal-face measurement. The standards differ, and the
 * difference is several percent on a real building."* It is written as an OPEN
 * QUESTION. It is not one — it has an answer, and the answer was sitting in the
 * geometry kernel the whole time.
 *
 * ⛔ MEASURED 2026-08-22, C01 §6 rule 6 (cite the command):
 *     grep -n "centerline" packages/geometry-kernel/src/producers/room.ts
 *   :59  "Wall ids whose CENTERLINE edge contributed to the boundary."
 *   :64  "Half-edge graph from wall CENTERLINES"
 *
 * Every `room.area` in this product is the area enclosed by the WALL
 * CENTRELINES. That is an exact measurement of a real thing — and it is NOT the
 * plane any published standard measures on:
 *
 *   SIA 416 NGF, IPMS 3, RICS NIA  → the INTERNAL dominant face  (centreline OVERSTATES)
 *   SIA 416 GF/BGF, IPMS 1, GEA    → the EXTERNAL face           (centreline UNDERSTATES)
 *
 * So the honest product is NOT "call the centreline sum GFA and move on". It is:
 * report the centreline figure AS the centreline figure, name every class of the
 * selected standard, and mark each one measured or not with the reason. The sign
 * of the error is KNOWN; that is worth far more than a plausible number.
 *
 * ═════════════════════════════════════════════════════════════════════════════
 * ⭐ WHICH STANDARD IS THE DEFAULT, AND WHY IT IS NOT SETTLED BY THE COUNT
 * ═════════════════════════════════════════════════════════════════════════════
 * The brief said: adopt SIA 416 as the default ONLY if it is already the
 * most-referenced standard in the repo; otherwise adopt the one the code leans
 * on. Both halves were measured, and the second one has no referent:
 *
 *   grep -rniE "\bSIA[ -]?416\b"  → 16 · IPMS → 4 · RICS (word-boundary) → 13
 *
 * ⚠ SIA leads — but EVERY ONE of those 16 is this product SAYING IT DOES NOT
 * HAVE IT: the `sia-416` refusal card, ADR-0343, the SPEC row, and a test. A
 * count generated by a refusal card is not the repo "leaning on" a standard; it
 * is the repo describing a hole, and reading it as adoption is the
 * [[confident-register-rows-are-the-wrong-ones]] trap exactly.
 *
 * ⛔ AND THE OTHER HALF IS EMPTY. There is NO standard the code leans on. The
 * only implemented area rule in the product is
 * `ScheduleExtractor.ts:567` — `actualGFA = Σ rooms[].computed.area` — which is
 * the centreline sum under a label ("GFA") that no standard would recognise for
 * it. That is not "leaning on RICS"; it is one line of arithmetic wearing an
 * acronym.
 *
 * So the default is SIA 416 on the brief's tie-break, and it is recorded here
 * that the count did not settle it — the count is self-referential and the
 * alternative was empty. It is SWITCHABLE, and switching is the point: the same
 * building has several different, all-correct areas, and this surface's job is
 * to make that visible rather than to pick one and hide the rest.
 *
 * L7 file. Frozen tables + module state. No THREE (P2), no rAF (P3), no
 * `(window as any)` (P4), no store writes (P6) — it reads no store at all;
 * `analysisReadModel.ts` owns every store read on this surface.
 */

import type { CoverageRow, CoverageState } from './AnalysisTypes';

/** The plane a class is measured on. The whole disagreement lives here. */
export type MeasurementPlane =
  /** Inner face of the enclosing construction. */
  | 'internal-face'
  /** Outer face of the external envelope. */
  | 'external-face'
  /** Wall centreline — what PRYZM's room producer actually uses. */
  | 'centreline'
  /** A derived ratio or a count, not an area measured on a plane. */
  | 'derived';

export type AreaStandardId = 'sia-416' | 'ipms' | 'rics-comp' | 'pryzm-centreline';

export interface AreaClassDef {
  /** The standard's own code — SIA writes GF/NGF/KF, IPMS writes IPMS 1..3. */
  readonly code: string;
  readonly label: string;
  readonly plane: MeasurementPlane;
  /**
   * ⛔ ADOPTED VERBATIM from the take-off's `CoverageState` (ADR-0343 §D.6).
   * A second three-state enum with slightly different names would be two
   * honesty vocabularies, which is zero honesty vocabularies.
   */
  readonly state: CoverageState;
  /** WHY, in words. A `NOT_MEASURED` class with no reason is a blank, not a fact. */
  readonly note: string;
}

export interface AreaStandardDef {
  readonly id: AreaStandardId;
  readonly label: string;
  /** Where it has force. A ratio means something different under another one. */
  readonly jurisdiction: string;
  readonly classes: readonly AreaClassDef[];
  /**
   * The one sentence the card prints on its face about THIS standard's relation
   * to what PRYZM can actually measure.
   */
  readonly verdict: string;
}

