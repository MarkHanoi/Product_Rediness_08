export const AREA_STANDARDS: readonly AreaStandardDef[] = Object.freeze([
  SIA_416,
  IPMS,
  RICS_COMP,
  PRYZM_CENTRELINE,
]);

/**
 * The default. See the header: the count that nominally chose it is
 * self-referential, and the alternative the brief offered ("the one the code
 * already leans on") has no referent. Recorded rather than presented as settled.
 */
export const DEFAULT_AREA_STANDARD: AreaStandardId = 'sia-416';

let _standard: AreaStandardId = DEFAULT_AREA_STANDARD;

export function areaStandard(): AreaStandardDef {
  return AREA_STANDARDS.find((s) => s.id === _standard) ?? SIA_416;
}

export function setAreaStandard(id: AreaStandardId): void {
  if (AREA_STANDARDS.some((s) => s.id === id)) _standard = id;
}

export function areaStandardById(id: string): AreaStandardDef | undefined {
  return AREA_STANDARDS.find((s) => s.id === id);
}

/**
 * The selected standard's class table, in the surface's coverage vocabulary.
 *
 * ⛔ The `family` column carries the standard's OWN code and its plane, so a
 * reader can see at a glance that seven rows say `internal-face` while the one
 * measured row says `centreline`. That single column is the whole argument of
 * this card, and it is data rather than prose.
 */
export function areaCoverageRows(std: AreaStandardDef = areaStandard()): readonly CoverageRow[] {
  return std.classes.map((c) => ({
    family: `${c.code} — ${c.label}  ·  plane: ${c.plane}`,
    state: c.state,
    note: c.note,
  }));
}
